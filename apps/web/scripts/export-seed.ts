import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { COURSE_DEFINITION } from "../src/data/carnival-course";
import { COURSE, pointAtMetre, projectOnCourse } from "../src/lib/course";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "backend", "seed");

const NOTE = "SAMPLE DATA, NOT OFFICIAL. Generated by apps/web/scripts/export-seed.ts: do not edit by hand.";

function write(name: string, data: unknown) {
  writeFileSync(join(OUT, name), JSON.stringify(data, null, 2) + "\n");
  console.log(`apps/backend/seed/${name}`);
}

const course = {
  _note: NOTE,
  id: COURSE.id,
  name: COURSE.name,
  official: COURSE.official,
  warning: COURSE.warning ?? null,
  geojson: {
    type: "Feature",
    properties: { name: "Senda del Carnaval (provisional)" },
    geometry: COURSE.geojson.geometry,
  },
  waypoints: COURSE.waypoints.map((w) => ({
    id: w.id,
    name: w.name,
    short: w.short,
    kind: w.kind,
    lat: w.lat,
    lng: w.lng,
    metres: w.metres,
    offsetM: w.offsetM,
  })),
};

function shift(p: { lat: number; lng: number }, d: number) {
  return { lat: p.lat + d, lng: p.lng + d };
}

function projections() {
  const coords = COURSE_DEFINITION.geojson.geometry.coordinates;
  const [lng0, lat0] = coords[0];
  const [lng1, lat1] = coords[1];
  const [lngN, latN] = coords[coords.length - 1];
  const [lngM, latM] = coords[coords.length - 2];
  const middle = pointAtMetre(COURSE.lengthMetres / 2);

  const points: { name: string; lat: number; lng: number }[] = [
    { name: "the start", lat: lat0, lng: lng0 },
    { name: "the end", lat: latN, lng: lngN },
    { name: "before the start", lat: lat0 - (lat1 - lat0) * 2, lng: lng0 - (lng1 - lng0) * 2 },
    { name: "after the end", lat: latN + (latN - latM) * 2, lng: lngN + (lngN - lngM) * 2 },
    { name: "the middle, on the course", ...middle },
    { name: "300 m east of the middle", lat: middle.lat, lng: middle.lng + 0.0027 },
    { name: "300 m west of the middle", lat: middle.lat, lng: middle.lng - 0.0027 },
    { name: "a quarter of the way, slightly off", ...shift(pointAtMetre(COURSE.lengthMetres / 4), 0.0003) },
    { name: "three quarters of the way, slightly off", ...shift(pointAtMetre((COURSE.lengthMetres * 3) / 4), -0.0004) },
    { name: "a vertex of the line", lat: coords[10][1], lng: coords[10][0] },
    { name: "the centre of Pasto, far from the course", lat: 1.2136, lng: -77.2811 },
  ];

  return {
    _note: NOTE,
    lengthM: COURSE.lengthMetres,
    points: points.map((p) => {
      const projection = projectOnCourse(p.lat, p.lng);
      return {
        ...p,
        metres: projection.metres,
        offsetM: projection.offsetM,
        snappedLat: projection.lat,
        snappedLng: projection.lng,
      };
    }),
  };
}

mkdirSync(OUT, { recursive: true });
write("course.json", course);
write("projections.json", projections());
