/**
 * Exports the web's sample data to `backend/seed/`, in the backend's English
 * contract (docs/backend/GLOSSARY.md), so `python -m app.cli seed` can load it.
 *
 *   npm run seed:export
 *
 * It also writes `projections.json`: points projected with turf, the way the
 * web does it. The backend's tests check that Python gives the same metres.
 *
 * THE DATA IS SAMPLE DATA: neither the course nor the dates are official.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import datosDesfiles from "../src/data/desfiles-ejemplo.json" with { type: "json" };
import { SENDA_DEFINICION } from "../src/data/senda-carnaval";
import { normalizarHora } from "../src/lib/fecha";
import { metrosEnSenda, puntoEnMetro, SENDA } from "../src/lib/senda";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "backend", "seed");

const WAYPOINT_KINDS: Record<string, string> = {
  iglesia: "church",
  comercial: "mall",
  colegio: "school",
  universidad: "university",
  plaza: "square",
  parque: "park",
  estadio: "stadium",
  hospital: "hospital",
};

function write(name: string, data: unknown) {
  writeFileSync(join(OUT, name), JSON.stringify(data, null, 2) + "\n");
  console.log(`backend/seed/${name}`);
}

const NOTE = "SAMPLE DATA, NOT OFFICIAL. Generated by scripts/export-seed.ts: do not edit by hand.";

const course = {
  _note: NOTE,
  id: "provisional-pasto-course",
  name: "Senda del Carnaval (trazado provisional)",
  official: SENDA.oficial,
  warning: SENDA.advertencia ?? null,
  geojson: {
    type: "Feature",
    properties: { name: "Senda del Carnaval (provisional)" },
    geometry: SENDA.geojson.geometry,
  },
  // The raw waypoints. `metres` and `offsetM` are turf's numbers, kept as a
  // reference: the backend projects them again when it loads the course.
  waypoints: SENDA.hitos.map((h) => ({
    id: h.id.replace(/^h-/, "w-"),
    name: h.nombre,
    short: h.corto,
    kind: WAYPOINT_KINDS[h.tipo],
    lat: h.lat,
    lng: h.lng,
    metres: h.metros,
    offsetM: h.desvioM,
  })),
};

const parades = {
  _note: NOTE,
  parades: datosDesfiles.dias.flatMap((dia) =>
    dia.eventos
      .filter((e) => e.esDesfile)
      .map((e) => ({ id: e.id, name: e.titulo, date: dia.fecha, startTime: normalizarHora(e.hora) })),
  ),
};

/** Points to compare against: on the course, off it and beyond both ends. */
function projections() {
  const coords = SENDA_DEFINICION.geojson.geometry.coordinates;
  const [lng0, lat0] = coords[0];
  const [lng1, lat1] = coords[1];
  const [lngN, latN] = coords[coords.length - 1];
  const [lngM, latM] = coords[coords.length - 2];
  const middle = puntoEnMetro(SENDA.longitudMetros / 2);

  const points: { name: string; lat: number; lng: number }[] = [
    { name: "the start", lat: lat0, lng: lng0 },
    { name: "the end", lat: latN, lng: lngN },
    // Continuing the first and last segments outwards.
    { name: "before the start", lat: lat0 - (lat1 - lat0) * 2, lng: lng0 - (lng1 - lng0) * 2 },
    { name: "after the end", lat: latN + (latN - latM) * 2, lng: lngN + (lngN - lngM) * 2 },
    { name: "the middle, on the course", ...middle },
    // ~300 m is about 0.0027 degrees at this latitude.
    { name: "300 m east of the middle", lat: middle.lat, lng: middle.lng + 0.0027 },
    { name: "300 m west of the middle", lat: middle.lat, lng: middle.lng - 0.0027 },
    { name: "a quarter of the way, slightly off", ...shift(puntoEnMetro(SENDA.longitudMetros / 4), 0.0003) },
    { name: "three quarters of the way, slightly off", ...shift(puntoEnMetro((SENDA.longitudMetros * 3) / 4), -0.0004) },
    { name: "a vertex of the line", lat: coords[10][1], lng: coords[10][0] },
    { name: "the centre of Pasto, far from the course", lat: 1.2136, lng: -77.2811 },
  ];

  return {
    _note: NOTE,
    lengthM: SENDA.longitudMetros,
    points: points.map((p) => {
      const proy = metrosEnSenda(p.lat, p.lng);
      return { ...p, metres: proy.metros, offsetM: proy.desvioM, snappedLat: proy.lat, snappedLng: proy.lng };
    }),
  };
}

function shift(p: { lat: number; lng: number }, d: number) {
  return { lat: p.lat + d, lng: p.lng + d };
}

mkdirSync(OUT, { recursive: true });
write("course.json", course);
write("parades.json", parades);
write("projections.json", projections());
